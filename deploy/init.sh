#!/usr/bin/env sh
# Write .env and start Comply. Run from this directory, or pass --no-start.
set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$ROOT"

NO_START=0
if [ "${1:-}" = "--no-start" ]; then
  NO_START=1
fi

SITENAME=${COMPLY_SITENAME:-localhost}
WEB_PORT=${WEB_PORT:-8080}
case "$SITENAME" in
  *://*) ORIGIN="$SITENAME" ;;
  localhost|127.0.0.1) ORIGIN="http://$SITENAME:$WEB_PORT" ;;
  localhost:*|127.0.0.1:*) ORIGIN="http://$SITENAME" ;;
  *) ORIGIN="https://$SITENAME" ;;
esac

random_hex() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 32
  else
    od -An -N32 -tx1 /dev/urandom | tr -d ' \n'
  fi
}

if [ ! -f .env ]; then
  cat > .env <<EOF
# Generated by deploy/init.sh. Keep this file private.
COMPLY_AUTH_SECRET=$(random_hex)
COMPLY_APP_URL=$ORIGIN
COMPLY_PUBLIC_URL=$ORIGIN
COMPLY_DEMO_LOGIN=0
COMPLY_INGEST_ON_START=1
COMPLY_INGEST_INTERVAL_HOURS=168
WEB_PORT=$WEB_PORT
# COMPLY_TRUST_HOST=trust.example.com
# COMPLY_TRUST_SLUG=nordwind

# Identity providers. Fill in the pairs you use and restart.
# COMPLY_OIDC_GOOGLE_CLIENT_ID=
# COMPLY_OIDC_GOOGLE_CLIENT_SECRET=
# COMPLY_OIDC_MICROSOFT_CLIENT_ID=
# COMPLY_OIDC_MICROSOFT_CLIENT_SECRET=
# COMPLY_OIDC_MICROSOFT_TENANT=common
# COMPLY_OIDC_GITHUB_CLIENT_ID=
# COMPLY_OIDC_GITHUB_CLIENT_SECRET=
EOF
  chmod 600 .env
  echo "Wrote $ROOT/.env"
else
  echo "Keeping the existing $ROOT/.env"
fi

if [ "$NO_START" -eq 1 ]; then
  echo "Start it with: cd $ROOT && docker compose up -d"
  exit 0
fi

if ! command -v docker >/dev/null 2>&1; then
  echo "error: Docker is not installed." >&2
  exit 1
fi
if ! docker compose version >/dev/null 2>&1; then
  echo "error: Docker Compose v2 is not available." >&2
  exit 1
fi

SAVED_PORT=$(grep '^WEB_PORT=' .env | tail -n 1 | cut -d= -f2- || true)
if [ -n "$SAVED_PORT" ]; then
  WEB_PORT="$SAVED_PORT"
fi

docker compose up -d

if command -v curl >/dev/null 2>&1; then
  tries=0
  while [ "$tries" -lt 60 ]; do
    if curl -fsS "http://127.0.0.1:$WEB_PORT/healthz" >/dev/null 2>&1; then
      break
    fi
    tries=$((tries + 1))
    sleep 2
  done
  if [ "$tries" -ge 60 ]; then
    echo "The container is still starting. Check: docker compose logs --tail=80"
  fi
fi

echo ""
echo "Comply is running at $ORIGIN"
echo "Open the URL and create the first account."
echo "That account becomes the administrator of this installation."
