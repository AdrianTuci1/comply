#!/usr/bin/env python3
"""Install Comply on a server without checking out the repository.

The script writes a small Compose project, generates the secrets, pulls the
published image, and waits for the health endpoint. Python 3.8+ and Docker
Compose v2 are the only requirements.
"""

from __future__ import annotations

import argparse
import re
import secrets
import shutil
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from urllib.parse import urlparse

DEFAULT_IMAGE = "ghcr.io/adriantuci1/comply"
DEFAULT_VERSION = "latest"
DEFAULT_PORT = 8080


def host_from(value: str, port: int | None = None) -> tuple[str, str]:
    """Return (origin, hostname) for a domain or a full URL."""
    raw = value.strip()
    if not raw:
        raise ValueError("--sitename is required.")
    if "://" not in raw:
        raw = f"http://{raw}" if raw.startswith(("localhost", "127.0.0.1")) else f"https://{raw}"
    parsed = urlparse(raw)
    if not parsed.hostname:
        raise ValueError(f"Invalid host: {value}")
    netloc = parsed.netloc
    if parsed.port is None and port and parsed.hostname in {"localhost", "127.0.0.1", "0.0.0.0", "::1"}:
        netloc = f"{parsed.hostname}:{port}"
    origin = f"{parsed.scheme}://{netloc}"
    return origin.rstrip("/"), parsed.hostname


def project_name(value: Path) -> str:
    name = re.sub(r"[^a-z0-9_-]+", "-", value.name.lower()).strip("-")
    return name or "comply"


def image_reference(image: str, version: str) -> str:
    last = image.rsplit("/", 1)[-1]
    if "@" in last or ":" in last:
        return image
    return f"{image}:{version}"


def read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value
    return values


def render_env(
    existing: dict[str, str],
    *,
    origin: str,
    port: int,
    trust_host: str,
    trust_slug: str,
    force: bool,
) -> str:
    auth_secret = "" if force else existing.get("COMPLY_AUTH_SECRET", "")
    if not auth_secret:
        auth_secret = secrets.token_hex(32)

    lines = [
        "# Generated by easy-install.py. Keep this file private.",
        f"COMPLY_AUTH_SECRET={auth_secret}",
        f"COMPLY_APP_URL={origin}",
        f"COMPLY_PUBLIC_URL={origin}",
        "COMPLY_DEMO_LOGIN=0",
        "COMPLY_INGEST_ON_START=1",
        "COMPLY_INGEST_INTERVAL_HOURS=168",
        f"WEB_PORT={port}",
    ]
    if trust_host:
        lines.append(f"COMPLY_TRUST_HOST={trust_host}")
        lines.append(f"COMPLY_TRUST_SLUG={trust_slug}")
    else:
        lines.append("# COMPLY_TRUST_HOST=trust.example.com")
        lines.append("# COMPLY_TRUST_SLUG=nordwind")
    lines.extend(
        [
            "",
            "# Identity providers. Fill in the pairs you use and restart.",
            "# COMPLY_OIDC_GOOGLE_CLIENT_ID=",
            "# COMPLY_OIDC_GOOGLE_CLIENT_SECRET=",
            "# COMPLY_OIDC_MICROSOFT_CLIENT_ID=",
            "# COMPLY_OIDC_MICROSOFT_CLIENT_SECRET=",
            "# COMPLY_OIDC_MICROSOFT_TENANT=common",
            "# COMPLY_OIDC_GITHUB_CLIENT_ID=",
            "# COMPLY_OIDC_GITHUB_CLIENT_SECRET=",
            "",
        ]
    )
    return "\n".join(lines)


def render_compose(name: str, image: str, data_dir: str) -> str:
    return f"""name: {name}

services:
  comply:
    image: {image}
    restart: unless-stopped
    env_file:
      - .env
    ports:
      - "${{WEB_PORT:-{DEFAULT_PORT}}}:8080"
    volumes:
      - "{data_dir}:/app/data"
"""


def write_private(path: Path, content: str) -> None:
    path.write_text(content, encoding="utf-8")
    path.chmod(0o600)


def docker_available() -> tuple[bool, str]:
    if not shutil.which("docker"):
        return False, "Docker is not installed. Install Docker Engine or Docker Desktop."
    probe = subprocess.run(
        ["docker", "compose", "version"],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        check=False,
    )
    if probe.returncode != 0:
        return False, "Docker Compose v2 is not available (docker compose version failed)."
    return True, ""


def wait_for_health(port: int, timeout: int = 120) -> bool:
    deadline = time.time() + timeout
    url = f"http://127.0.0.1:{port}/healthz"
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(url, timeout=3) as response:
                if response.status == 200:
                    return True
        except (urllib.error.URLError, TimeoutError, OSError):
            pass
        time.sleep(2)
    return False


def deploy(args: argparse.Namespace) -> int:
    root = Path(args.project).expanduser().resolve()
    root.mkdir(parents=True, exist_ok=True)
    env_path = root / ".env"
    compose_path = root / "docker-compose.yml"

    origin, _ = host_from(args.sitename, args.port)
    if not 1 <= args.port <= 65535:
        raise ValueError("--port must be between 1 and 65535.")

    existing = read_env(env_path)
    trust_host = args.trust_host.strip()
    trust_slug = args.trust_slug.strip() or "nordwind"
    if trust_host and "://" in trust_host:
        _, trust_host = host_from(trust_host)

    env_text = render_env(
        existing,
        origin=origin,
        port=args.port,
        trust_host=trust_host,
        trust_slug=trust_slug,
        force=args.force,
    )
    data_dir = args.data
    if not Path(data_dir).is_absolute():
        data_dir = f"./{data_dir}"
    compose_text = render_compose(
        project_name(root),
        image_reference(args.image, args.version),
        data_dir,
    )

    write_private(env_path, env_text)
    compose_path.write_text(compose_text, encoding="utf-8")

    print(f"Configuration written to {root}")
    print(f"  {compose_path.name}")
    print(f"  .env (mode 600)")

    if args.no_start:
        print("")
        print("Start it with:")
        print(f"  cd {root} && docker compose up -d")
        return 0

    ready, reason = docker_available()
    if not ready:
        print(f"error: {reason}", file=sys.stderr)
        return 1

    print("Pulling the image and starting the container...")
    started = subprocess.run(
        ["docker", "compose", "up", "-d"],
        cwd=root,
        check=False,
    )
    if started.returncode != 0:
        print("error: docker compose up failed. Run it in the project directory for details.", file=sys.stderr)
        return started.returncode

    healthy = wait_for_health(args.port)
    print("")
    if healthy:
        print(f"Comply is running at {origin}")
    else:
        print(f"Comply started, but {origin} did not answer /healthz within 120 seconds.")
        print(f"Check the logs: cd {root} && docker compose logs --tail=80")
    print("")
    print("Open the URL and create the first account.")
    print("That account becomes the administrator of this installation.")
    if trust_host:
        print(f"Trust page: {origin} (set the DNS CNAME to this server, keep the Host header)")
    print(f"Data: {root / args.data}")
    return 0 if healthy else 1


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Install Comply without checking out the repository.",
    )
    parser.add_argument("--version", action="version", version="comply 0.1.0")
    subparsers = parser.add_subparsers(dest="command")
    deploy_parser = subparsers.add_parser("deploy", help="write the Compose project and start it")
    deploy_parser.add_argument("--project", default="comply", help="project directory (default: comply)")
    deploy_parser.add_argument("--sitename", required=True, help="public hostname, for example comply.example.com")
    deploy_parser.add_argument("--image", default=DEFAULT_IMAGE, help=f"container image (default: {DEFAULT_IMAGE})")
    deploy_parser.add_argument("--version", default=DEFAULT_VERSION, help="image tag (default: latest)")
    deploy_parser.add_argument("--port", type=int, default=DEFAULT_PORT, help="host port (default: 8080)")
    deploy_parser.add_argument("--data", default="data", help="host data directory (default: data)")
    deploy_parser.add_argument("--trust-host", default="", help="public trust hostname, for example trust.example.com")
    deploy_parser.add_argument("--trust-slug", default="nordwind", help="tenant slug for the trust page")
    deploy_parser.add_argument("--no-start", action="store_true", help="write the files without starting Docker")
    deploy_parser.add_argument("--force", action="store_true", help="rotate generated secrets")
    return parser


def main(argv: list[str]) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(line_buffering=True)
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.command != "deploy":
        parser.print_help()
        return 0
    try:
        return deploy(args)
    except (ValueError, OSError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
